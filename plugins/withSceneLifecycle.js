// Apps built with the iOS 27 SDK (Xcode 27) must adopt the UIScene life cycle,
// otherwise iOS refuses to launch them and they sit on the splash screen:
// "Application failed to launch: UIScene life cycle is required for apps built with this SDK".
// Expo SDK 54 still generates a window-based AppDelegate, so this plugin adds a scene
// manifest to Info.plist and a SceneDelegate to AppDelegate.swift.
//
// The window is still created in AppDelegate — SDK 54 native modules (expo-dev-launcher
// in particular) expect it to exist at launch — and the scene only adopts it.
//
// Applied to the dev variant only (see app.config.js): release builds are made on EAS
// with the Xcode that SDK 54 targets and don't need this. Remove once the project is
// on an Expo SDK that adopts scenes itself.
const {
  withAppDelegate,
  withInfoPlist,
  WarningAggregator,
} = require("expo/config-plugins");

const MARKER = "// @horosho/scene-lifecycle";

const SCENE_DELEGATE = `
${MARKER}
// Generated by plugins/withSceneLifecycle.js — edit the plugin, not this file.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  private var appDelegate: AppDelegate? {
    UIApplication.shared.delegate as? AppDelegate
  }

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
          let window = appDelegate?.window else { return }
    window.windowScene = windowScene
    self.window = window
    window.makeKeyAndVisible()
  }

  // With scenes, links and life cycle events arrive here instead of in AppDelegate;
  // forward them so Expo subscribers and RCTLinkingManager keep working.
  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let url = URLContexts.first?.url else { return }
    _ = appDelegate?.application(UIApplication.shared, open: url, options: [:])
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = appDelegate?.application(UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }

  func sceneDidBecomeActive(_ scene: UIScene) {
    appDelegate?.applicationDidBecomeActive(UIApplication.shared)
  }

  func sceneWillResignActive(_ scene: UIScene) {
    appDelegate?.applicationWillResignActive(UIApplication.shared)
  }

  func sceneWillEnterForeground(_ scene: UIScene) {
    appDelegate?.applicationWillEnterForeground(UIApplication.shared)
  }

  func sceneDidEnterBackground(_ scene: UIScene) {
    appDelegate?.applicationDidEnterBackground(UIApplication.shared)
  }
}
`;

function withSceneManifest(config) {
  return withInfoPlist(config, (config) => {
    config.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: "Default Configuration",
            UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
          },
        ],
      },
    };
    return config;
  });
}

function withSceneDelegate(config) {
  return withAppDelegate(config, (config) => {
    const { language, contents } = config.modResults;
    if (contents.includes(MARKER)) return config;

    if (language !== "swift" || !/class AppDelegate\b/.test(contents)) {
      WarningAggregator.addWarningIOS(
        "withSceneLifecycle",
        "AppDelegate выглядит не так, как ожидалось — SceneDelegate не добавлен."
      );
      return config;
    }

    config.modResults.contents = contents.trimEnd() + "\n" + SCENE_DELEGATE;
    return config;
  });
}

module.exports = function withSceneLifecycle(config) {
  return withSceneDelegate(withSceneManifest(config));
};
